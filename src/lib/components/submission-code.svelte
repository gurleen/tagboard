<script lang="ts">
	import { renderSVG } from 'uqr';
	import type { SubmissionCodePosition } from '$lib/database/schema';
	import { submissionUrl } from '$lib/submission/endpoints';

	/**
	 * The QR code an output draws in one corner, linking to the public submission
	 * page. Styled with the board's custom properties, like the rest of the output.
	 *
	 * The code itself is always dark on light, whatever the theme: an inverted code
	 * is one many phone cameras will not read.
	 */
	let {
		position,
		submissionKey
	}: { position: Exclude<SubmissionCodePosition, 'hidden'>; submissionKey: string } = $props();

	const markup = $derived(
		renderSVG(submissionUrl(location.origin, submissionKey), { border: 2, ecc: 'M' })
	);
</script>

<aside class="submission-code {position}" aria-label="Scan to share a photo">
	<!-- Generated by `uqr` from the URL alone; it contains no outside markup. -->
	<!-- eslint-disable-next-line svelte/no-at-html-tags -->
	<div class="code">{@html markup}</div>
	<div class="caption">Scan to share a photo</div>
</aside>

